NAME = re.compile(r"^[a-z0-9][a-z0-9_.-]{0,63}$")


def check_name(name, what="name"):
    if not NAME.match(name):
        raise ValueError(f"{what} {name!r}: use 1-64 lowercase letters, digits, '_', '-' or '.'")
    return name


def machine_label(label=None):
    label = label or os.environ.get("BENCH_MACHINE") or f"{platform.system()}-{platform.machine()}".lower()
    return check_name(label, "machine label")


def replace_with_retries(source, target, attempts=8):
    """os.replace, retried: on Windows, Defender or the indexer briefly locks new files (WinError 5)."""
    for attempt in range(attempts):
        try:
            os.replace(source, target)
            return
        except PermissionError:
            if attempt == attempts - 1:
                raise
            time.sleep(0.1 * 2 ** attempt)


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=1, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
    replace_with_retries(temporary, path)
    return path


def write_npy(path, array):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp.npy")
    np.save(temporary, array)
    replace_with_retries(temporary, path)
    return path


def git_info():
    def git(*args):
        return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True, check=True).stdout.strip()
    try:
        return {"commit": git("rev-parse", "HEAD"), "dirty": bool(git("status", "--porcelain", "--untracked-files=no"))}
    except (OSError, subprocess.CalledProcessError):
        return {"commit": None, "dirty": None}


def load_registry():
    return json.loads(REGISTRY.read_text(encoding="utf-8")) if REGISTRY.exists() else {}


def save_registry(registry):
    write_json(REGISTRY, dict(sorted(registry.items())))


def result_path(bench, model, machine):
    return RESULTS / bench / f"{model}@{machine}.json"


def load_results(bench=None):
    folders = [RESULTS / bench] if bench else [p for p in sorted(RESULTS.glob("*")) if p.is_dir() and p.name not in ("latency", "aihub")]
    return [json.loads(p.read_text(encoding="utf-8")) for f in folders for p in sorted(f.glob("*@*.json"))]


def find_result(bench, model, machine=None):
    matches = [r for r in load_results(bench) if r["model"]["name"] == model
               and (machine is None or r["machine"]["label"] == machine)]
    if not matches:
        raise ValueError(f"No result for model {model!r} on benchmark {bench!r}"
                         + (f" from machine {machine!r}" if machine else ""))
    return matches[0]


def load_latency_sessions():
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RESULTS / "latency").glob("*.json"))]


def load_aihub_sessions():
    """On-device runs on Qualcomm AI Hub hosted phones: bench/results/aihub/<model>@<device>_<utc>.json."""
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((RESULTS / "aihub").glob("*.json"))]


# ---- LEADERBOARD.md ----

def _fmt(x, digits=4):
    return "-" if x is None else f"{x:.{digits}f}"


def _count(n):
    return "-" if n is None else f"{n:,}"


def _params(e):
    return "-" if not e else f"{e['initializer_elements']:,}"


def leaderboard_markdown(results, sessions, definitions, aihub=()):
    lines = ["# Team leaderboard", "",
             "Generated by `python -m bench leaderboard` from `bench/results/`; do not edit by hand. "
             "Local evaluation on BOXRR-23 players, not the challenge's hidden test set.", ""]
    for bench in sorted({r["bench"]["name"] for r in results}):
        rows = [r for r in results if r["bench"]["name"] == bench]
        d = definitions.get(bench, {})
        ranked = sorted((r for r in rows if r["contamination"]["status"] == "clean"),
                        key=lambda r: r["accuracy"]["mean_deg_step20"])
        flagged = [r for r in rows if r["contamination"]["status"] != "clean"]
        best = ranked[0] if ranked else None
        no_ci = False
        lines += [f"## Benchmark `{bench}`", "",
                  f"{len(rows[0]['bench']['players'])} players, {rows[0]['bench']['windows']:,} windows, cohort "
                  f"fingerprint `{rows[0]['bench']['cohort_fingerprint'][:16]}`. {d.get('description', '')}", "",
                  "Error = mean geodesic angle (degrees) over all windows at step 20 (200 ms ahead, the scored step) "
                  "and step 10 (100 ms). Stateful graphs: streamed from segment start (headline) and from a cold start "
                  "at the first full window. Delta vs #1: window-weighted mean difference, 95% interval from a paired "
                  "bootstrap over players.", "",
                  "| # | Model | Error 200 ms (°) | Δ vs #1 (°), 95% CI | Cold start (°) | Error 100 ms (°) | "
                  "Median / p95 (°) | Equal-player (°) | ONNX params | Declared params | MACs per call | Audit issues | "
                  "Machine | Commit |",
                  "| ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |"]
        for i, r in enumerate(ranked + flagged):
            a, e, m = r["accuracy"], r.get("efficiency"), r["model"]
            rank = str(i + 1) if r in ranked else "⚠"
            delta = "-"
            if best is not None and r is not best:
                if stats.has_per_player(a) and stats.has_per_player(best["accuracy"]):
                    p = stats.paired(a, best["accuracy"])
                    delta = f"{p['mean_diff_deg']:+.4f} [{p['ci95'][0]:+.3f}, {p['ci95'][1]:+.3f}]"
                else:  # same windows, so this equals the paired mean difference; only the interval is missing
                    no_ci = True
                    delta = f"{a['mean_deg_step20'] - best['accuracy']['mean_deg_step20']:+.4f} (no CI)"
            cold = r.get("accuracy_cold_start")
            macs = f"{e['macs_per_call']['total']:,}" if e else "-"
            issues = ", ".join(e["operators"]["issues"]) if e else ""
            lines.append(f"| {rank} | {m['name']}{' (stateful)' if m.get('stateful') else ''} | "
                         f"{_fmt(a['mean_deg_step20'])} | {delta} | {_fmt(cold['mean_deg_step20']) if cold else '-'} | "
                         f"{_fmt(a['mean_deg_step10'])} | {_fmt(a['median_deg_step20'], 3)} / {_fmt(a['p95_deg_step20'], 3)} | "
                         f"{_fmt(a['equal_player_mean_deg_step20'])} | {_params(e)} | "
                         f"{_count(m.get('declared_trainable_parameters'))} | {macs} | {issues or 'none'} | "
                         f"{r['machine']['label']} | {(r['git']['commit'] or '-')[:7]}{'+' if r['git']['dirty'] else ''} |")
        if flagged:
            lines += ["", "⚠ = not ranked: " + "; ".join(
                f"{r['model']['name']} is {r['contamination']['status']}"
                + (f" ({len(r['contamination']['overlap'])} benchmark players in its training data)"
                   if r["contamination"]["overlap"] else "") for r in flagged) + "."]
        if no_ci:
            lines += ["", "(no CI) = the difference of the two means only. The interval needs per-player sums, which "
                          "published results leave out; re-score both models with `python -m bench score` to get it."]
        groups = {}
        for r in ranked:
            if r["model"].get("group"):
                groups.setdefault(r["model"]["group"], []).append(r)
        if groups:
            lines += ["", "**Seed groups** (each member is a separate artefact above; the challenge scores one).", "",
                      "| Group | Members | Mean ± sd, 200 ms (°) |", "| --- | ---: | ---: |"]
            for g, members in sorted(groups.items()):
                values = np.array([r["accuracy"]["mean_deg_step20"] for r in members])
                sd = f"{values.std(ddof=1):.4f}" if len(values) > 1 else "-"
                lines.append(f"| {g} | {len(values)} | {values.mean():.4f} ± {sd} |")
        lines.append("")
    if sessions:
        lines += ["## Latency sessions", "",
                  "Local ONNX Runtime CPU timings, batch 1, one harness step per call. **Each table is one session on one "
                  "machine; never compare numbers across tables.** Not ST's XR target.", ""]
        for s in sessions:
            mach, proto = s["machine"], s["protocol"]
            lines += [f"### {s['label']} · {s['created_utc'][:16].replace('T', ' ')} UTC", "",
                      f"{mach['cpu']} · {mach['os']} · {mach['logical_cores']} logical cores · ONNX Runtime "
                      f"{mach['onnxruntime']} · {proto['timed_calls']:,} timed calls per model in {proto['rounds']} "
                      f"alternating rounds after {proto['warmup_per_round']} warm-up calls each.", "",
                      "| Model | Threads | Median (ms) | p90 (ms) | p99 (ms) |", "| --- | ---: | ---: | ---: | ---: |"]
            ordered = sorted(s["models"].items(), key=lambda kv: min(t["median_ms"] for t in kv[1]["threads"].values()))
            for name, entry in ordered:
                for t, v in sorted(entry["threads"].items(), key=lambda kv: int(kv[0])):
                    lines.append(f"| {name}{' (stateful)' if entry['stateful'] else ''} | {t} | {v['median_ms']:.3f} | "
                                 f"{v['p90_ms']:.3f} | {v['p99_ms']:.3f} |")
            lines.append("")
    if aihub:
        lines += ["## On-device runs (Qualcomm AI Hub)", "",
                  "Hosted Snapdragon phones on Qualcomm AI Hub Workbench. Time per call is AI Hub's "
                  "`estimated_inference_time` over its own loop of up to 100 calls on random inputs (AI Hub does not "
                  "say whether it is a mean, median or minimum), so it is not comparable with the CPU sessions above. "
                  "Parity: angle between the device's prediction and ONNX Runtime float32 on the same inputs (stream "
                  "snapshots with warm states). Still not ST's XR target.", "",
                  "| Model | Device | Chipset | Runtime | Time per call (µs) | Layers | Parity mean / max (°) | Date |",
                  "| --- | --- | --- | --- | ---: | --- | ---: | --- |"]
        for s in aihub:
            for run in s["runs"]:
                layers = ", ".join(f"{k} {v}" for k, v in sorted(run.get("layers_by_compute_unit", {}).items())) or "-"
                parity = (f"{run['parity_mean_deg']:.3f} / {run['parity_max_deg']:.3f}"
                          if run.get("parity_mean_deg") is not None else "-")
                time_us = run.get("estimated_inference_time_us")
                lines.append(f"| {s['model']['name']} | {s['device']['name']} | {s['device']['chipset']} | "
                             f"{run['runtime']} | {_count(time_us)} | {layers} | {parity} | "
                             f"{s['created_utc'][:10]} |")
        lines.append("")
    return "\n".join(lines)


def write_leaderboard(path=LEADERBOARD):
    from bench.data import DEFINITIONS
    definitions = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in DEFINITIONS.glob("*.json")}
    text = leaderboard_markdown(load_results(), load_latency_sessions(), definitions, load_aihub_sessions())
    Path(path).write_text(text, encoding="utf-8")
    return path
